#!/usr/bin/env python3
"""Run official GRIT Peptides jobs with a task-aware 1-hop control.

This is the HPC analogue of the Peptides Colab runners. It uses the official
LiamMa/GRIT checkout and official Peptides config for the dense baseline. For
the 1-hop sparse control, it copies the official config and changes only:

  gt.attn.full_attn: False
  gt.attn.sparsity: one_hop

The masked RRWP encoder implementation is supplied by the shared GRIT patch
applied in ``prepare_grit_repo.sh``.
"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[4]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


TASKS: dict[str, dict[str, str]] = {
    "struct": {
        "dataset_name": "peptides-structural",
        "official_cfg": "configs/GRIT/peptides-struct-GRIT-RRWP.yaml",
        "onehop_cfg": "configs/GRIT/peptides-struct-GRIT-RRWP-1hop.yaml",
        "name_tag": "slurm.peptides_struct.official.GRITwRRWP",
        "onehop_name_tag": "slurm.peptides_struct.1hop.GRITwRRWP",
    },
    "func": {
        "dataset_name": "peptides-functional",
        "official_cfg": "configs/GRIT/peptides-func-GRIT-RRWP.yaml",
        "onehop_cfg": "configs/GRIT/peptides-func-GRIT-RRWP-1hop.yaml",
        "name_tag": "slurm.peptides_func.official.GRITwRRWP",
        "onehop_name_tag": "slurm.peptides_func.1hop.GRITwRRWP",
    },
}

PARAM_RE = re.compile(r"Num parameters:\s*([0-9,]+)")


class PatchLog:
    @staticmethod
    def log(message: str) -> None:
        print(message, flush=True)

    @staticmethod
    def run_cmd(cmd: list[str], *, check: bool = True, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
        print("[cmd] " + " ".join(map(str, cmd)), flush=True)
        proc = subprocess.run(cmd, cwd=str(cwd) if cwd else None, text=True, check=False)
        if check and proc.returncode != 0:
            raise RuntimeError(f"command failed with exit code {proc.returncode}: {' '.join(map(str, cmd))}")
        return proc


def _set_nested(payload: dict[str, Any], path: tuple[str, ...], value: Any) -> None:
    current: dict[str, Any] = payload
    for key in path[:-1]:
        current = current.setdefault(key, {})
    current[path[-1]] = value


def make_onehop_config(repo_dir: Path, task: str) -> Path:
    import yaml

    info = TASKS[task]
    official = repo_dir / info["official_cfg"]
    onehop = repo_dir / info["onehop_cfg"]
    if not official.exists():
        raise FileNotFoundError(f"official Peptides config is missing: {official}")
    cfg = yaml.safe_load(official.read_text(encoding="utf-8"))
    _set_nested(cfg, ("gt", "attn", "full_attn"), False)
    _set_nested(cfg, ("gt", "attn", "sparsity"), "one_hop")
    _set_nested(cfg, ("mlflow", "name"), Path(info["onehop_cfg"]).stem)
    if "wandb" in cfg:
        cfg["wandb"]["use"] = False
    header = (
        f"# Parameter-matched 1-hop sparse-control variant of {info['official_cfg']}.\n"
        "# Generated by experiments/peptides/grit_official_slurm/scripts/run_grit_peptides_slurm.py.\n"
        "# Only gt.attn.full_attn=False and gt.attn.sparsity=one_hop change the model path.\n"
    )
    onehop.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    return onehop


def apply_runtime_patches(repo_dir: Path, *, recovery: bool) -> None:
    from experiments.peptides_struct.training import grit_peptides_struct_common as peptides_common

    peptides_common.apply_peptides_dataset_compat_patch(PatchLog, repo_dir)
    peptides_common.apply_peptides_streaming_rrwp_patch(PatchLog, repo_dir)
    if recovery:
        from experiments.zinc.training import grit_zinc_core

        grit_zinc_core.apply_recovery_checkpoint_patch(repo_dir)
        grit_zinc_core.verify_recovery_checkpoint_patch(repo_dir)


def build_command(args: argparse.Namespace) -> list[str]:
    info = TASKS[args.task]
    cfg = info["onehop_cfg"] if args.variant == "1hop" else info["official_cfg"]
    name_tag = resolved_name_tag(args)
    cmd = [
        args.python,
        "-u",
        "main.py",
        "--cfg",
        cfg,
        "--repeat",
        str(args.repeat),
        "wandb.use",
        "False",
        "accelerator",
        args.accelerator,
        "dataset.dir",
        str(args.data_dir),
        "out_dir",
        str(args.out_dir),
        "seed",
        str(args.seed),
        "name_tag",
        name_tag,
        "train.eval_period",
        "1",
        "train.enable_ckpt",
        "True",
        "train.ckpt_period",
        str(args.ckpt_period),
        "train.ckpt_best",
        "True",
        "train.ckpt_clean",
        "False",
        "train.auto_resume",
        "True",
        "num_threads",
        str(args.num_threads),
    ]
    if args.max_epoch is not None:
        cmd.extend(["optim.max_epoch", str(args.max_epoch)])
    cmd.extend(args.cfg_overrides)
    return cmd


def resolved_name_tag(args: argparse.Namespace) -> str:
    info = TASKS[args.task]
    return args.name_tag or (info["onehop_name_tag"] if args.variant == "1hop" else info["name_tag"])


def run_and_guard(args: argparse.Namespace) -> int:
    repo_dir = args.repo_dir.resolve()
    if not (repo_dir / "main.py").is_file():
        raise FileNotFoundError(f"GRIT repo does not contain main.py: {repo_dir}")

    args.data_dir.mkdir(parents=True, exist_ok=True)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    log_dir = args.out_dir / "slurm_logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    log_file = log_dir / f"{args.task}_{args.variant}_seed{args.seed}_{stamp}.log"

    if args.variant == "1hop":
        cfg_path = make_onehop_config(repo_dir, args.task)
        print(f"[config] wrote 1-hop Peptides config: {cfg_path}", flush=True)
    apply_runtime_patches(repo_dir, recovery=not args.no_recovery_patch)

    cmd = build_command(args)
    env = os.environ.copy()
    env["PYTHONUNBUFFERED"] = "1"
    env["GRIT_PE_STREAM_CHUNK_SIZE"] = str(max(1, int(args.rrwp_stream_chunk_size)))
    if not args.no_recovery_patch:
        name_tag = resolved_name_tag(args)
        recovery_dir = (
            args.out_dir
            / "_recovery_checkpoints"
            / f"{args.task}_{args.variant}_seed{args.seed}_{re.sub(r'[^A-Za-z0-9_.-]+', '_', name_tag)}"
        )
        recovery_dir.mkdir(parents=True, exist_ok=True)
        env["GRIT_FORCE_RECOVERY_CKPT"] = "1"
        env["GRIT_RECOVERY_CKPT_PERIOD"] = str(max(0, int(args.recovery_ckpt_period)))
        env["GRIT_RECOVERY_CKPT_DIR"] = str(recovery_dir)
        env["GRIT_SAVE_FIRST_RECOVERY_CKPT"] = "1"
        print(f"[checkpoint] stable recovery dir: {recovery_dir}", flush=True)

    print("[run] " + " ".join(map(str, cmd)), flush=True)
    print(f"[run] cwd={repo_dir}", flush=True)
    print(f"[run] log={log_file}", flush=True)

    saw_params = False
    with log_file.open("w", encoding="utf-8") as log:
        log.write("[run] " + " ".join(map(str, cmd)) + "\n")
        log.write(f"[run] cwd={repo_dir}\n")
        proc = subprocess.Popen(
            cmd,
            cwd=repo_dir,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1,
        )
        assert proc.stdout is not None
        for line in proc.stdout:
            sys.stdout.write(line)
            sys.stdout.flush()
            log.write(line)
            log.flush()
            match = PARAM_RE.search(line)
            if match and not saw_params:
                saw_params = True
                actual = int(match.group(1).replace(",", ""))
                msg = f"[param-check] observed={actual}"
                if args.expected_params is not None:
                    msg += f" expected={args.expected_params}"
                msg += "\n"
                sys.stdout.write(msg)
                sys.stdout.flush()
                log.write(msg)
                log.flush()
                if args.expected_params is not None and actual != args.expected_params and not args.allow_param_count_drift:
                    err = "[param-check:ERROR] Parameter count mismatch; terminating.\n"
                    sys.stdout.write(err)
                    sys.stdout.flush()
                    log.write(err)
                    proc.terminate()
                    try:
                        proc.wait(timeout=30)
                    except subprocess.TimeoutExpired:
                        proc.kill()
                        proc.wait()
                    return 2
        rc = proc.wait()

    if not saw_params:
        print("[param-check:ERROR] Did not observe `Num parameters:` in GRIT output.")
        return 3 if rc == 0 else rc
    return rc


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-dir", type=Path, required=True)
    parser.add_argument("--task", choices=sorted(TASKS), required=True)
    parser.add_argument("--variant", choices=["official", "1hop"], required=True)
    parser.add_argument("--data-dir", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--accelerator", default="cuda:0")
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--name-tag", default=None)
    parser.add_argument("--max-epoch", type=int, default=None)
    parser.add_argument("--ckpt-period", type=int, default=100)
    parser.add_argument("--recovery-ckpt-period", type=int, default=100)
    parser.add_argument("--rrwp-stream-chunk-size", type=int, default=32)
    parser.add_argument("--num-threads", type=int, default=8)
    parser.add_argument("--expected-params", type=int, default=None)
    parser.add_argument("--allow-param-count-drift", action="store_true")
    parser.add_argument("--no-recovery-patch", action="store_true")
    parser.add_argument("cfg_overrides", nargs=argparse.REMAINDER)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    return run_and_guard(args)


if __name__ == "__main__":
    raise SystemExit(main())
